def bidi(p):
    pPr=p._p.get_or_add_pPr(); e=OxmlElement('w:bidi');e.set(qn('w:val'),'1');pPr.append(e)

def set_run(run,size=10.5,bold=False,color=INK):
    run.font.name=AR_FONT;run._element.rPr.rFonts.set(qn('w:cs'),AR_FONT);run.font.size=Pt(size);run.bold=bold;run.font.color.rgb=RGBColor.from_string(color)

def para(doc,text='',style=None,size=10.5,bold=False,color=INK,after=5,align=WD_ALIGN_PARAGRAPH.RIGHT):
    p=doc.add_paragraph(style=style);p.alignment=align;bidi(p);p.paragraph_format.space_after=Pt(after);p.paragraph_format.line_spacing=1.12;set_run(p.add_run(str(text)),size,bold,color);return p

def shade(cell,color):
    tcPr=cell._tc.get_or_add_tcPr();shd=OxmlElement('w:shd');shd.set(qn('w:fill'),color);tcPr.append(shd)

def cell_text(cell,text,bold=False,color=INK,size=8.5):
    cell.text='';p=cell.paragraphs[0];p.alignment=WD_ALIGN_PARAGRAPH.RIGHT;bidi(p);p.paragraph_format.space_after=Pt(0);set_run(p.add_run(str(text)),size,bold,color);cell.vertical_alignment=WD_CELL_VERTICAL_ALIGNMENT.CENTER

def table(doc,heads,rows,widths=None,size=8.5):
    t=doc.add_table(rows=1,cols=len(heads));t.style='Table Grid';t.alignment=WD_TABLE_ALIGNMENT.CENTER
    for c,h in zip(t.rows[0].cells,heads):shade(c,NAVY);cell_text(c,h,True,WHITE,size)
    trPr=t.rows[0]._tr.get_or_add_trPr();h=OxmlElement('w:tblHeader');h.set(qn('w:val'),'true');trPr.append(h)
    for ri,row in enumerate(rows):
        cells=t.add_row().cells
        for c,v in zip(cells,row):
            if ri%2==0:shade(c,LIGHT)
            cell_text(c,v,False,INK,size)
    if widths:
        for row in t.rows:
            for c,w in zip(row.cells,widths): c.width=Inches(w)
    return t

