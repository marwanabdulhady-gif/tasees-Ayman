  const PAGE_TO_WEEKS = new Map();
  WEEKS.forEach((wk) => {
    (wk.maps || []).forEach((m) => {
      if (!PAGE_TO_WEEKS.has(m.page)) PAGE_TO_WEEKS.set(m.page, []);
      const arr = PAGE_TO_WEEKS.get(m.page);
      if (!arr.some((x) => x.id === wk.id)) arr.push(wk);
    });
  });

  function getWeeksForPage(pageId) {
    return PAGE_TO_WEEKS.get(pageId) || [];
  }

  function getUnitByNumber(uNum) {
    return UNITS.find((u) => u.u === Number(uNum)) || null;
  }

  function getWeekById(weekId) {
    if (!weekId) return null;
    const clean = String(weekId).trim().toLowerCase();
    if (/^\d+$/.test(clean)) {
      const n = Number(clean);
      return WEEKS.find((w) => w.w === n) || null;
    }
    return WEEKS.find((w) => w.id.toLowerCase() === clean) || null;
  }

  function getMapPageIdsForFilter(filterKey) {
    if (!filterKey || filterKey === "all") return null;
    const set = new Set();
    if (filterKey.startsWith("u")) {
      const uNum = Number(filterKey.slice(1));
      WEEKS.filter((w) => w.u === uNum).forEach((w) => {
        (w.maps || []).forEach((m) => set.add(m.page));
      });
      return set;
    }
    if (filterKey.startsWith("w")) {
      const wk = getWeekById(filterKey);
      if (wk) (wk.maps || []).forEach((m) => set.add(m.page));
      return set;
    }
    if (filterKey.startsWith("tr-")) {
      const sr = LECTURE_SERIES.find((s) => s.id === filterKey);
      if (sr) (sr.featuredMaps || []).forEach((m) => set.add(m.page));
      return set;
    }
    return null;
  }

