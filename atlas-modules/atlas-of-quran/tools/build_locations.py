import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent.parent
QURAN = json.loads((HERE / "data" / "quran-uthmani.json").read_text(encoding="utf-8"))["verses"]

DIAC = re.compile(r"[ؐ-ًؚ-ٰٟۖ-ۭـ]")


def norm(t):
    t = DIAC.sub("", t).replace("ٱ", "ا")
    t = re.sub("[أإآ]", "ا", t).replace("ى", "ي").replace("ة", "ه")
    return " " + re.sub(r"\s+", " ", t).strip() + " "


def skel(w):
    return re.sub("[اويءئؤ]", "", norm(w).strip())


def excerpt(ref, hint):
    """Exact Uthmani words of `ref` whose letter skeleton matches `hint` (hint is only a locator)."""
    words = QURAN[ref].split()
    target = [skel(w) for w in hint.split()]
    real = [(i, skel(w)) for i, w in enumerate(words) if skel(w)]   # skip stand-alone pause marks (ۖ ۚ …)
    sk = [s for _, s in real]
    for j in range(len(sk) - len(target) + 1):
        if sk[j:j + len(target)] == target:
            first, last = real[j][0], real[j + len(target) - 1][0]
            return " ".join(words[first:last + 1])
    raise SystemExit(f"excerpt not found in {ref}: «{hint}»")


